import { translateTimetableEntryError } from '../db/database-errors.js';
import { toApiEntry, toEngineEntry } from './entry-mappers.js';

/**
 * Condition matching the entries a section attends: its own classes and combined classes.
 *
 * @param {string} sectionId Section id.
 * @returns {object} Prisma where fragment.
 */
export function sectionFilter(sectionId) {
  return { OR: [{ sectionId }, { coSectionIds: { has: sectionId } }] };
}

/** Columns read for list views; skips bulky audit text, which keeps the hot read path light. */
const LIST_COLUMNS = Object.freeze({
  id: true,
  versionId: true,
  sectionId: true,
  coSectionIds: true,
  subjectId: true,
  facultyId: true,
  roomId: true,
  day: true,
  slotId: true,
  sessionType: true,
  isElective: true
});

/**
 * Convert a joined row into an entry that also carries display names for calendar events.
 *
 * @param {object} row Prisma entry including subject, room and faculty.
 * @returns {object}
 */
function toDetailedEntry(row) {
  return {
    ...toApiEntry(row),
    subjectCode: row.subject.code,
    subjectName: row.subject.name,
    roomName: row.room.name,
    building: row.room.building,
    facultyName: row.faculty.name
  };
}

/**
 * Data access for timetable entries.
 *
 * @param {import('@prisma/client').PrismaClient | import('@prisma/client').Prisma.TransactionClient} db Prisma client or transaction.
 */
export function createTimetableEntryRepository(db) {
  return {
    /**
     * Insert one entry. Unique and foreign-key violations become application errors.
     *
     * @param {object} entry Entry fields including id and versionId.
     * @returns {Promise<object>} The stored entry.
     */
    async insert(entry) {
      try {
        const row = await db.timetableEntry.create({
          data: {
            id: entry.id,
            versionId: entry.versionId,
            sectionId: entry.sectionId,
            coSectionIds: entry.coSectionIds ?? [],
            subjectId: entry.subjectId,
            facultyId: entry.facultyId,
            roomId: entry.roomId,
            day: entry.day,
            slotId: entry.slot,
            sessionType: entry.sessionType ?? 'LECTURE',
            isElective: Boolean(entry.isElective)
          }
        });
        return toApiEntry(row);
      } catch (error) {
        throw translateTimetableEntryError(error, entry);
      }
    },

    /**
     * Insert many entries at once. Used for versions generated by the system, whose entries
     * were already checked against the hard constraints.
     *
     * @param {object[]} rows Prisma create-data rows.
     * @returns {Promise<number>} Number of inserted entries.
     */
    async insertMany(rows) {
      if (rows.length === 0) return 0;
      const { count } = await db.timetableEntry.createMany({ data: rows });
      return count;
    },

    /**
     * List the entries of a version, ordered by time slot.
     *
     * @param {string} versionId Version id.
     * @param {{ sectionId?: string, day?: string }} [filters] Optional filters.
     * @returns {Promise<object[]>}
     */
    async findByVersion(versionId, { sectionId, day } = {}) {
      const rows = await db.timetableEntry.findMany({
        where: { versionId, ...(day ? { day } : {}), ...(sectionId ? sectionFilter(sectionId) : {}) },
        select: LIST_COLUMNS,
        orderBy: [{ slotId: 'asc' }, { id: 'asc' }]
      });
      return rows.map(toApiEntry);
    },

    /**
     * List the entries of the ACTIVE version in one query (no separate lookup of the version).
     *
     * @param {{ sectionId?: string, day?: string }} [filters] Optional filters.
     * @returns {Promise<object[]>}
     */
    async findInActiveVersion({ sectionId, day } = {}) {
      const rows = await db.timetableEntry.findMany({
        where: { version: { status: 'ACTIVE' }, ...(day ? { day } : {}), ...(sectionId ? sectionFilter(sectionId) : {}) },
        select: LIST_COLUMNS,
        orderBy: [{ slotId: 'asc' }, { id: 'asc' }]
      });
      return rows.map(toApiEntry);
    },

    /**
     * List the entries of a version in the shape used by the scheduling engines.
     *
     * @param {string} versionId Version id.
     * @returns {Promise<object[]>}
     */
    async findForEngine(versionId) {
      const rows = await db.timetableEntry.findMany({
        where: { versionId },
        select: LIST_COLUMNS,
        orderBy: [{ day: 'asc' }, { slotId: 'asc' }, { id: 'asc' }]
      });
      return rows.map(toEngineEntry);
    },

    /**
     * List the entries of a version together with subject, room and faculty names.
     *
     * @param {string} versionId Version id.
     * @param {{ sectionId?: string, facultyId?: string }} [filters] Optional filters.
     * @returns {Promise<object[]>}
     */
    async findDetailed(versionId, { sectionId, facultyId } = {}) {
      const rows = await db.timetableEntry.findMany({
        where: { versionId, ...(facultyId ? { facultyId } : {}), ...(sectionId ? sectionFilter(sectionId) : {}) },
        include: { subject: true, room: true, faculty: true },
        orderBy: [{ day: 'asc' }, { slotId: 'asc' }]
      });
      return rows.map(toDetailedEntry);
    },

    /**
     * Count the entries of a version.
     *
     * @param {string} versionId Version id.
     * @returns {Promise<number>}
     */
    countByVersion(versionId) {
      return db.timetableEntry.count({ where: { versionId } });
    }
  };
}
